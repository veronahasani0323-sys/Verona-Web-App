// Vercel build: copy the static app into dist/ and write config.js from environment variables.
// No dependencies. Run locally with: SUPABASE_URL=... SUPABASE_PUBLISHABLE_KEY=... node scripts/build.mjs
import { mkdirSync, copyFileSync, writeFileSync, cpSync } from "node:fs";

const url = (process.env.SUPABASE_URL || "").trim();
const key = (process.env.SUPABASE_PUBLISHABLE_KEY || process.env.SUPABASE_ANON_KEY || "").trim();

if (url && !/^https:\/\/[^/]+$/.test(url.replace(/\/$/, ""))) {
  console.error(`SUPABASE_URL should look like https://<project>.supabase.co, got "${url}"`);
  process.exit(1);
}
if (key && /service_role|sb_secret_/.test(key)) {
  console.error("That is a secret key. Use the publishable (or anon) key: the secret key must never reach the browser.");
  process.exit(1);
}

mkdirSync("dist", { recursive: true });
for (const f of ["index.html", "manifest.webmanifest"]) copyFileSync(f, `dist/${f}`);
cpSync("icons", "dist/icons", { recursive: true });
writeFileSync("dist/config.js",
  "// Generated by scripts/build.mjs\nwindow.PD_CONFIG = " +
  JSON.stringify({ supabaseUrl: url.replace(/\/$/, ""), supabaseKey: key }) + ";\n");

console.log(url && key
  ? `Built dist/ with Supabase: ${url}`
  : "Built dist/ WITHOUT Supabase (env vars missing): the deployed app will save to each browser only.");
